def toml_value(v):
    """A TOML value: literal strings for regular expressions, JSON-compatible otherwise."""
    if isinstance(v, str):
        return "'" + v + "'" if "'" not in v and "\n" not in v else json.dumps(v, ensure_ascii=False)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    return json.dumps(v)


def checks_section(config):
    """One [checks.<id>] table per check: the effective settings as comments, with where they come from."""
    levels = " | ".join(f'"{k}"' for k in LEVELS)
    out = [
        "# Every check: `enabled` (true/false) and `level` – how much its findings weigh:",
        *(f"#   {k:<10} {v}" for k, v in LEVELS.items()),
        "# Values shown are the effective ones (defaults, or set by a rule pack); uncomment a line to override it.",
    ]
    for m in CHECKS:
        settings = config.check_config[m.ID]
        pack = getattr(m, "PACK", None)
        out += ["", f"[checks.{m.ID}]  # {m.TITLE}" + (f" – only with the pack '{pack}'" if pack else "")]
        for key, (value, source) in settings.items():
            about = levels if key == "level" else ("" if key == "enabled" else m.OPTIONS[key]["about"])
            note = f"  # {about}" if about else ""
            src = f" (from {source})" if source != "default" else ""
            line = f"{key} = {toml_value(value)}"
            out.append((line if source == "configuration file" else "# " + line) + note + src)
    return "\n".join(out)


def spawn_config(repo, config):
    """A starting configuration: the inferred project facts, packs, every check with its settings, examples."""
    resolve_project(repo, config)
    packs = "\n".join(f"#   {k:<9} {'(default) ' if d['default'] else ''}{d['about']}" for k, d in PACKS.items())
    return f"""# {TOOL_NAME} – configuration for {os.path.basename(repo.root)}
# Generated by --spawn-config from what the repository itself declares. Review every value: the report shows
# which values were inferred and which were configured. Run: oss-readiness-audit <repository> -c <this file>

[project]
# Name prefixes of the project's own bundles/packages (inferred from the Bundle-SymbolicNames).
own_prefixes = {toml_value(config.project["own_prefixes"])}
# Product name(s), case-sensitive regular expressions (inferred from .product files / the root POM).
name_patterns = {toml_value(config.project["name_patterns"])}
# Accepted Bundle-Vendor / provider-name values (others are listed for review).
vendors = []
# Foundations hosting the project, by name root (e.g. ["org.eclipse"]): own names under them are then expected.
hosted_by = []

[scan]
# Paths not scanned at all (globs; '**' spans folders), e.g. vendored third-party copies.
exclude = []
# Unpacked built products whose jars are inventoried, and OSV dumps (relative to this file).
products = []
osv_db = []

[packs]
# Rule packs:
{packs}
enable = {toml_value(config.packs["enable"])}
disable = {toml_value(config.packs["disable"])}

[rules]
# Additions to the built-in rule packs (regular expressions, case-insensitive unless noted).
proprietary = []        # proprietary license clauses; a named group (?P<holder>…) captures the owner
ownership = []          # ownership / confidentiality wording
public_hosts = []       # domains that are public (not reported as hosts)
internal_host_hints = []
namespace_allow = []    # accepted foreign nsURIs
# bundle_to_maven = {{ "org.example.repackaged" = "org.example:artifact" }}

[scenario]
move_out = []           # units to move out of the publication (glob on name, path or family)

{checks_section(config)}

# Acknowledge reviewed findings; they are listed in the report as acknowledged, with the reason.
# [[suppress]]
# check = "secrets"            # check id, or "*"
# path = "**/src/test/**"      # glob on the file path (optional)
# text = "dummy"               # regex on the finding text (optional)
# reason = "test fixtures with dummy credentials"
"""


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog=TOOL_ID, description="Offline open-source readiness audit of a source tree (Eclipse/OSGi/Tycho aware)."
    )
    ap.add_argument("--version", action="version", version=f"%(prog)s {TOOL_VERSION}")
    ap.add_argument("repository", help="path of the repository (a git checkout or a plain folder)")
    ap.add_argument("-o", "--output", default="oss-readiness-report.html", help="HTML report (one self-contained file)")
    ap.add_argument("-c", "--config", help="TOML configuration (see --spawn-config)")
    ap.add_argument(
        "--spawn-config",
        "--init-config",
        dest="spawn_config",
        action="store_true",
        help="print a configuration for this repository – inferred project facts, packs, every check with its "
        "settings – and exit (combine with --pack, -c to start from those)",
    )
    ap.add_argument("--json", action="store_true", help="also write the findings as JSON next to the report")
    ap.add_argument(
        "--product", action="append", default=[], help="unpacked product folder whose jars are inventoried (repeatable)"
    )
    ap.add_argument(
        "--osv-db", action="append", default=[], help="OSV dump zip (e.g. Maven/all.zip, npm/all.zip; repeatable)"
    )
    ap.add_argument(
        "--own-prefix",
        action="append",
        default=[],
        help="name prefix of the project's own bundles and "
        "artifacts (repeatable; default: inferred from the bundle names)",
    )
    ap.add_argument(
        "--name-pattern",
        action="append",
        default=[],
        help="regular expression for the product name "
        "(case-sensitive; repeatable; default: inferred from .product files and the root POM)",
    )
    ap.add_argument(
        "--pack",
        action="append",
        default=[],
        metavar="[no-]PACK",
        help="enable an optional rule pack, or disable a default one with 'no-' (e.g. no-lang-de) "
        f"({', '.join(PACKS)})",
    )
    ap.add_argument(
        "--exclude-path",
        action="append",
        default=[],
        metavar="GLOB",
        help="do not scan these paths (e.g. vendored copies); repeatable",
    )
    ap.add_argument(
        "--move-out",
        action="append",
        default=[],
        metavar="PATTERN",
        help="scenario: units to move out (glob on bundle/module name, path or family; repeatable)",
    )
    ap.add_argument(
        "--anonymise-path", action="store_true", help="show only the folder name of the repository in the report"
    )
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    try:
        config = Config(args.config, vars(args))
    except (OSError, ValueError, tomllib.TOMLDecodeError) as e:
        ap.error(f"configuration: {e}")
    for p in config.osv_db + config.products + [args.repository]:
        if not os.path.exists(p):
            ap.error(f"not found: {p}")
    repo = Repo(args.repository, config.exclude)
    if args.spawn_config:
        sys.stdout.write(spawn_config(repo, config))
        return 0
    if not args.quiet:
        print(
            f"Auditing {repo.root} ({len(repo.files):,} files{', git ' + repo.git['head'][:10] if repo.git else ''})",
            file=sys.stderr,
        )
    data = build_report(repo, config, args.quiet)
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(render_html(data))
    jpath = None
    if args.json:
        jpath = os.path.splitext(args.output)[0] + ".json"
        with open(jpath, "w", encoding="utf-8") as fh:
            json.dump(data, fh, ensure_ascii=False, indent=1)
    if not args.quiet:
        c = Counter(ch["status"] for ch in data["checks"])
        cfg = data["config"]
        print(
            f"Own prefixes ({cfg['own_prefixes_source']}): {', '.join(cfg['own_prefixes']) or 'none'}; "
            f"packs: {', '.join(cfg['packs'])}",
            file=sys.stderr,
        )
        print(
            f"Report: {args.output}"
            + (f"\nData:   {jpath}" if jpath else "")
            + f"\nResult: {c['blocker']} blocker, {c['judgement']} need judgement, "
            f"{c['clear']} clear, {c['not_run']} not run" + (f", {c['info']} for information" if c["info"] else ""),
            file=sys.stderr,
        )
    return 0
