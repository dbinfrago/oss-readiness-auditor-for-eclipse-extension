import re
from collections import Counter

from ..common import SOURCE_EXT, ext

ID = "ownerless"
GROUP = "legal"
TITLE = "Source files without an owner"
ICON = "binary"
# Why the check matters for publication
WHY = "Files without a known copyright holder cannot be relicensed by anyone."
# What resolves its findings, for readers who decide rather than fix
RESOLVE = (
    "Establish who wrote these files (history, contracts) and add their copyright line, or document that a "
    "contributor agreement covers them."
)

HEADERLESS_LINES = 40


def bundle_of(rel):
    parts = rel.split("/")
    for i in range(len(parts) - 1, 0, -1):
        if parts[i] in ("src", "src-gen", "xtend-gen", "test", "tests") and i > 0:
            return "/".join(parts[:i])
    return "/".join(parts[:-1]) or "."


def run(ctx, c):
    repo = ctx.repo
    c.rule(
        "No owner",
        f"Source files ({', '.join(sorted(SOURCE_EXT))}) whose first {HEADERLESS_LINES} lines contain "
        "neither 'Copyright', '©' nor 'SPDX-"
        "FileCopyrightText', and that have no REUSE side-car file (<file>.license) naming a copyright holder.",
    )
    c.rule(
        "Generated code",
        "Reported separately, because their header comes from the generator (e.g. the genmodel "
        "copyrightText): files in src-gen/, xtend-gen/, gen/, generated/ folders, and files marked as generated "
        "(@generated / @Generated, 'Generated by', 'DO NOT EDIT', EMF begin-user-doc tags).",
    )
    per_bundle, generated = Counter(), 0
    gen_mark = re.compile(
        r"@generated\b|@Generated\b|<!--\s*begin-user-doc\s*-->|\bGenerated\s+by\b|"
        r"\bDO\s+NOT\s+EDIT\b|\bautomatically\s+generated\b",
        re.I,
    )
    sidecars = {f[: -len(".license")] for f in repo.files if f.endswith(".license")}
    for f in repo.files:
        if ext(f) not in SOURCE_EXT:
            continue
        if f in sidecars and re.search(r"SPDX-" "FileCopyrightText:", repo.text(f + ".license") or ""):
            continue
        t = repo.text(f)
        if t is None:
            continue
        head = "\n".join(t.splitlines()[:HEADERLESS_LINES])
        if re.search(r"(?i)copyright|©|SPDX-" "FileCopyrightText", head):
            continue
        if re.search(r"(^|/)(src-gen|xtend-gen|gen|generated|src_gen)/", f) or gen_mark.search(t[:20000]):
            generated += 1
            continue
        if c.add(f, None, "", bundle_of(f)):
            per_bundle[bundle_of(f)] += 1
    n = sum(per_bundle.values())
    c.figure = f"{n:,}"
    c.figure_label = "hand-written source files without copyright holder"
    c.finding = (
        f"{n:,} hand-written source files in {len(per_bundle)} folders name no copyright holder; "
        f"{generated:,} further files in generated-code folders."
    )
    c.tables.append(
        {
            "caption": "Folders with the most files without owner",
            "columns": ["Folder", "Files"],
            "rows": [[b, k] for b, k in per_bundle.most_common(20)],
        }
    )
    c.status = "judgement" if n else "clear"
    return c
